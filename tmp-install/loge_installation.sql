create or replace function public.loge_location_creer(p_token text,p jsonb) returns int language plpgsql security definer set search_path=public as $$
declare x jsonb; n int:=0;
begin
  if not loge_ok(p_token) then raise exception 'session'; end if;
  for x in select * from jsonb_array_elements(p->'costumes') loop
    insert into loge_locations(rdv_id,client,tel,costume_id,costume_nom,univers,taille,depart,retour_prevu,prix,caution,note)
    values(nullif(p->>'rdv_id','')::uuid,p->>'client',p->>'tel',nullif(x->>'id','')::bigint,x->>'nom',(select univers from loge_costumes where id=nullif(x->>'id','')::bigint),x->>'taille',coalesce((p->>'depart')::date,current_date),(p->>'retour')::date,(x->>'prix')::numeric,(p->>'caution')::numeric,p->>'note');
    n:=n+1;
  end loop;
  if (p->>'rdv_id') is not null then update loge_rdv set statut='venu',maj=now() where id=(p->>'rdv_id')::uuid; end if;
  return n;
end $$;
