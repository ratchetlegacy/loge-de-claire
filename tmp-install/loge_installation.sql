create or replace function public.loge_rdv_envoyer(p jsonb) returns void language plpgsql security definer set search_path=public as $$
begin
  if coalesce(trim(p->>'nom'),'')='' or coalesce(trim(p->>'tel'),'')='' then raise exception 'incomplet'; end if;
  if (select count(*) from loge_rdv where cree>now()-interval '1 hour')>=30 then raise exception 'trop_de_demandes'; end if;
  if exists(select 1 from loge_rdv where jour=(p->>'jour')::date and creneau=p->>'creneau' and statut<>'annulé') then raise exception 'creneau_pris'; end if;
  insert into loge_rdv(jour,creneau,nom,tel,nb,theme,note,favoris) values((p->>'jour')::date,left(p->>'creneau',10),left(p->>'nom',120),left(p->>'tel',40),left(p->>'nb',20),left(p->>'theme',120),left(p->>'note',1000),coalesce(p->'favoris','[]'::jsonb));
end $$;
