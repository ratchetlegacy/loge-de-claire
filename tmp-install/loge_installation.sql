create table public.loge_contenu(cle text primary key, valeur jsonb not null, maj timestamptz not null default now());
create table public.loge_rdv(id uuid primary key default gen_random_uuid(), cree timestamptz not null default now(), jour date not null, creneau text not null, nom text not null, tel text not null, nb text, theme text, note text, favoris jsonb not null default '[]'::jsonb, statut text not null default 'à confirmer' check (statut in ('à confirmer','confirmé','annulé','venu','venu sans location','absent')), maj timestamptz not null default now());
create index loge_rdv_jour on public.loge_rdv(jour);
create table public.loge_locations(id uuid primary key default gen_random_uuid(), cree timestamptz not null default now(), rdv_id uuid references public.loge_rdv(id), client text not null, tel text, costume_id bigint references public.loge_costumes(id), costume_nom text not null, univers text, taille text, depart date not null default current_date, retour_prevu date not null, rendu date, prix numeric(10,2), caution numeric(10,2), note text, sms_retard timestamptz);
create index loge_locations_encours on public.loge_locations(costume_id) where rendu is null;
create table public.loge_admin(id int primary key default 1 check (id=1), hash text not null, echecs int not null default 0, bloque_jusqu timestamptz);
create table public.loge_sessions(token text primary key, expire timestamptz not null);
