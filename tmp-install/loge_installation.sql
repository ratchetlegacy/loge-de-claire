create or replace function public.loge_init(p_mdp text) returns text language plpgsql security definer set search_path=public,extensions as $$
declare t text;
begin
  if exists(select 1 from loge_admin) then raise exception 'deja_configure'; end if;
  if length(coalesce(p_mdp,''))<8 then raise exception 'mdp_court'; end if;
  insert into loge_admin(id,hash) values(1,crypt(p_mdp,gen_salt('bf',10)));
  t:=encode(gen_random_bytes(32),'hex'); insert into loge_sessions values(t,now()+interval '90 days'); return t;
end $$;
create or replace function public.loge_connexion(p_mdp text) returns text language plpgsql security definer set search_path=public,extensions as $$
declare a loge_admin; t text;
begin
  select * into a from loge_admin where id=1;
  if a is null then raise exception 'non_configure'; end if;
  if a.bloque_jusqu is not null and a.bloque_jusqu>now() then raise exception 'bloque'; end if;
  if a.hash<>crypt(coalesce(p_mdp,''),a.hash) then
    if a.echecs+1>=5 then update loge_admin set echecs=0,bloque_jusqu=now()+interval '15 minutes' where id=1; else update loge_admin set echecs=a.echecs+1 where id=1; end if;
    return null; end if;
  update loge_admin set echecs=0,bloque_jusqu=null where id=1;
  t:=encode(gen_random_bytes(32),'hex'); insert into loge_sessions values(t,now()+interval '90 days'); return t;
end $$;
create or replace function public.loge_mdp_changer(p_token text,p_ancien text,p_nouveau text) returns boolean language plpgsql security definer set search_path=public,extensions as $$
declare a loge_admin;
begin
  if not loge_ok(p_token) then raise exception 'session'; end if;
  select * into a from loge_admin where id=1;
  if a.hash<>crypt(coalesce(p_ancien,''),a.hash) then return false; end if;
  if length(coalesce(p_nouveau,''))<8 then raise exception 'mdp_court'; end if;
  update loge_admin set hash=crypt(p_nouveau,gen_salt('bf',10)) where id=1;
  update loge_sessions set expire=now() where token<>p_token; return true;
end $$;
