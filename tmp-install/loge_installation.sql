create extension if not exists pgcrypto with schema extensions;

create table public.loge_univers(id text primary key, label text not null, bg text not null default '#3B2416', ordre int not null default 100);
create table public.loge_costumes(id bigint generated by default as identity primary key, ref text unique, nom text not null, univers text not null references public.loge_univers(id), descr text not null default '', photo text, tailles jsonb not null default '[]'::jsonb, prix numeric(10,2), actif boolean not null default true, cree timestamptz not null default now(), maj timestamptz not null default now());
