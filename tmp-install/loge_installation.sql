create or replace function public.loge_ok(p_token text) returns boolean language sql security definer set search_path=public as $$
  select exists(select 1 from loge_sessions where token=p_token and expire>now());
$$;
create or replace function public.loge_tailles(p_id bigint, p_t jsonb) returns jsonb language sql stable security definer set search_path=public as $$
  select coalesce(jsonb_agg(jsonb_build_object('s',t->>'s','n',(t->>'n')::int,
    'f',greatest(0,(t->>'n')::int-(select count(*) from loge_locations l where l.costume_id=p_id and l.taille=t->>'s' and l.rendu is null)),
    'r',(select min(retour_prevu) from loge_locations l where l.costume_id=p_id and l.taille=t->>'s' and l.rendu is null)) order by o),'[]'::jsonb)
  from jsonb_array_elements(p_t) with ordinality as x(t,o);
$$;
