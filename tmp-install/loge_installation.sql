create or replace function public.loge_import(p_token text,p_rows jsonb) returns jsonb language plpgsql security definer set search_path=public as $$
declare r jsonb; u text; c int:=0; m int:=0; ex bigint;
begin
  if not loge_ok(p_token) then raise exception 'session'; end if;
  for r in select * from jsonb_array_elements(p_rows) loop
    u:=r->>'univers';
    if not exists(select 1 from loge_univers where id=u) then insert into loge_univers(id,label) values(u,coalesce(r->>'univers_label',u)); end if;
    ex:=null;
    if coalesce(r->>'ref','')<>'' then select id into ex from loge_costumes where ref=r->>'ref'; end if;
    if ex is null then select id into ex from loge_costumes where lower(nom)=lower(r->>'nom') and univers=u and actif limit 1; end if;
    if ex is null then
      insert into loge_costumes(ref,nom,univers,descr,tailles,prix) values(nullif(r->>'ref',''),r->>'nom',u,coalesce(r->>'descr',''),coalesce(r->'tailles','[]'),(r->>'prix')::numeric); c:=c+1;
    else
      update loge_costumes set nom=r->>'nom',univers=u,descr=case when coalesce(r->>'descr','')<>'' then r->>'descr' else descr end,tailles=coalesce(r->'tailles',tailles),prix=coalesce((r->>'prix')::numeric,prix),actif=true,maj=now() where id=ex; m:=m+1;
    end if;
  end loop;
  return jsonb_build_object('crees',c,'maj',m);
end $$;
